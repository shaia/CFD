/** Linear interpolation of a DNS profile at an arbitrary y+.
 *  Returns -1.0 when y+ lies outside the tabulated range (never extrapolates). */
static inline double channel_dns_interp(const double* yp, const double* vals,
                                        size_t n, double yplus) {
    if (n < 2 || yplus < yp[0] || yplus > yp[n - 1]) {
        return -1.0;
    }
    for (size_t i = 1; i < n; i++) {
        if (yplus <= yp[i]) {
            double t = (yplus - yp[i - 1]) / (yp[i] - yp[i - 1]);
            return vals[i - 1] + t * (vals[i] - vals[i - 1]);
        }
    }
    return vals[n - 1];
}

