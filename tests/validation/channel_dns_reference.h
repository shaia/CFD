/**
 * @file channel_dns_reference.h
 * @brief DNS reference profiles for turbulent plane channel flow.
 *
 * Ground truth for turbulence-model validation. The log-law check in
 * test_turbulent_channel.c cannot measure closure error on its own: the wall
 * function IMPOSES log-law behaviour at the first node, so scoring the profile
 * against the log law is close to circular. (Observed: k-epsilon and
 * Spalart-Allmaras agree on u_tau to four significant figures despite being
 * structurally different models; against DNS they separate cleanly.)
 *
 * Source: https://turbulence.oden.utexas.edu/  (MKM data sets)
 *   Moser, Kim & Mansour, "DNS of Turbulent Channel Flow up to Re_tau=590",
 *   Physics of Fluids 11(4), 943-945, 1999.
 *   Numerical method: Kim, Moin & Moser, J. Fluid Mech. 177, 133-166, 1987.
 *   Files: chan<N>/profiles/chan<N>.means and chan<N>.reystress
 *
 * Normalization: velocities by u_tau, lengths by h, stresses by u_tau^2. So
 * UPLUS is u+, KPLUS is k+, and UVPLUS is -<u'v'>+ directly.
 *
 * KPLUS and UVPLUS are derived from the published Reynolds-stress components:
 *   k+     = 0.5 * (R_uu + R_vv + R_ww)
 *   -uv+   = -R_uv          (positive in the lower half of the channel)
 *
 * NOTE: the nominal case names (395, 590) are labels; the ACTUAL friction
 * Reynolds numbers are 392.24 and 587.19. Drive the solver at the actual value
 * when comparing, or the comparison carries a systematic offset.
 *
 * Generated programmatically from the downloaded data files, not transcribed.
 */

